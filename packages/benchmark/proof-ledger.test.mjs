import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import test from 'node:test';

const repoRoot = resolve(import.meta.dirname, '..', '..');
const ledgerPath = resolve(repoRoot, 'docs', 'plans', '2026-05-23-stax-api-performance-proof-ledger.md');

function readLedger() {
  return readFileSync(ledgerPath, 'utf8');
}

function claimRow(markdown, id) {
  const row = markdown.split(/\r?\n/).find((line) => line.startsWith(`| \`${id}\` |`));
  assert.ok(row, `missing claim row: ${id}`);
  return row;
}

test('proof ledger keeps runtime-limit claims below conclusion strength', () => {
  const markdown = readLedger();
  assert.match(markdown, /## Proof Vocabulary/);
  assert.match(markdown, /## Current Evidence: Object-Shape Parity/);
  assert.match(markdown, /## Current Evidence: Woodstox HotSpot Trace/);
  assert.match(markdown, /## Current Evidence: Woodstox JFR Allocation Sampling/);
  assert.match(markdown, /## Current Evidence: Rust quick-xml Shape Audit/);
  assert.match(markdown, /## Current Evidence: Monomorphic Materialization Counters/);
  assert.match(markdown, /## Current Evidence: V8 Monomorphic Shape Trace/);
  assert.match(markdown, /## Current Evidence: V8 Allocation Sampling/);
  assert.match(markdown, /## Current Evidence: 1 GiB Generated Byte-Batch Shape/);
  assert.match(markdown, /## Required Proof Tracks/);
  assert.match(markdown, /## Current Next Experiments/);

  assert.match(claimRow(markdown, 'CLAIM-JS-RUNTIME-LIMIT-200MIB'), /\| `HYPOTHESIS` \|/);
  assert.match(claimRow(markdown, 'CLAIM-WOODSTOX-SAME-JS-OBJECTS'), /\| `COUNTEREXAMPLE` \|/);
  assert.match(claimRow(markdown, 'CLAIM-QUICKXML-SAME-DATA'), /\| `SOURCE_FACT` \+ `BENCH_FACT` \+ partial `TRACE_FACT` \|/);
  assert.match(claimRow(markdown, 'CLAIM-QUICKXML-SAME-JS-OBJECTS'), /\| `COUNTEREXAMPLE` \|/);
  assert.match(claimRow(markdown, 'CLAIM-LAZY-GETTERS'), /\| `NEGATIVE_RESULT` \|/);
  assert.match(claimRow(markdown, 'CLAIM-JS-STRING-ZERO-COPY'), /\| `ENGINE_INVARIANT`/);

  assert.doesNotMatch(markdown, /JavaScript runtimes cannot exceed 200 MiB\/s/i);
  assert.match(markdown, /Any 200 MiB\/s\+ bounded-memory JS row is a counterexample/);
  assert.match(markdown, /object-shape-parity\.md/);
  assert.match(markdown, /woodstox-hotspot-trace\.md/);
  assert.match(markdown, /woodstox-jfr-allocation\.md/);
  assert.match(markdown, /woodstox-measured-jfr-allocation\.md/);
  assert.match(markdown, /quick-xml-shape-audit\.md/);
  assert.match(markdown, /quick-xml-allocation-count\.md/);
  assert.match(markdown, /monomorphic-batch-access\.md/);
  assert.match(markdown, /v8-monomorphic-shape-trace\.md/);
  assert.match(markdown, /v8-allocation-sampling\.md/);
  assert.match(markdown, /v8-allocation-sampling-diverse\.md/);
  assert.match(markdown, /event-reader-object/);
  assert.match(markdown, /less-repetitive generated/);
  assert.match(markdown, /two-sample evidence/);
  assert.match(markdown, /stream-reader-1gb-shapes\.md/);
  assert.match(markdown, /stream-reader-1gb-diverse-shapes\.md/);
  assert.match(markdown, /stream-reader-1gb-allocation-shapes\.md/);
  assert.match(markdown, /stream-reader-1gb-allocation-diverse-shapes\.md/);
  assert.match(markdown, /without V8\s+HeapProfiler allocation sampling overhead/);
  assert.match(markdown, /`warmups=0`, and `runs=3`/);
  assert.match(markdown, /generated byte-batch shape with\s+V8 HeapProfiler allocation sampling/);
  assert.match(markdown, /4,096-row deterministic\s+`diverse-cycle` fixture/);
  assert.match(markdown, /not an allocation profile/);
  assert.match(markdown, /not prove a 200 MiB\/s JavaScript runtime ceiling/);
  assert.match(markdown, /not a proof that no further JavaScript headroom exists/);
  assert.match(markdown, /does not cover Bun\/JSC or browser engines/);
  assert.match(markdown, /not a global runtime-limit\s+proof/);
  assert.match(markdown, /not an allocation profile or machine-code\s+trace/);
  assert.match(markdown, /Rust global allocator counter/);
  assert.match(markdown, /170,824\s+allocation operations/);
  assert.match(markdown, /284,695 borrowed and 0 owned/);
  assert.match(markdown, /escaped, non-ASCII, or mixed-encoding fixtures/);
  assert.match(markdown, /does\s+not prove a\s+JavaScript runtime ceiling/);
  assert.match(markdown, /sampled JFR allocation stacks/);
  assert.match(markdown, /TextBuffer\.contentsAsString/);
  assert.match(markdown, /after warmups and after the pre-run\s+`System\.gc\(\)`/);
  assert.match(markdown, /It is allocation-path evidence, not a\s+speed baseline/);
  assert.match(markdown, /not a deterministic allocation census/);
});
