import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..', '..');
const tmpDir = join(__dirname, 'results', 'tmp', 'text-materialization-frontier-report-test');
const jsonOut = join(tmpDir, 'text-materialization-frontier.json');
const mdOut = join(tmpDir, 'text-materialization-frontier.md');

test('text materialization frontier separates headroom rows from full-string counterexamples', () => {
  resetTmp();
  const result = spawnSync(process.execPath, [
    join(__dirname, 'text-materialization-frontier.mjs'),
    '--json-out',
    jsonOut,
    '--md-out',
    mdOut,
  ], {
    cwd: repoRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  assert.equal(result.status, 0, result.stderr || result.stdout);

  const report = JSON.parse(readFileSync(jsonOut, 'utf8'));
  assert.equal(report.objective, 'text-materialization-frontier');
  assert.equal(report.contract, 'same-corpus-text-materialization-headroom-synthesis');
  assert.equal(report.summary.targetMiBPerSec, 200);
  assert.equal(report.summary.fullRowCount, 4);
  assert.equal(report.summary.nearFullWithoutTextRowCount, 4);
  assert.equal(report.summary.fullRowsCrossTarget, 0);
  assert.equal(report.summary.noTextRowsCrossTarget, 4);
  assert.equal(report.summary.noTrimRowsCrossTarget, 0);
  assert.equal(report.summary.foldTrimRowsCrossTarget, 0);
  assert.equal(report.summary.fastestFull.id, 'rawFrameNameId');
  assert.equal(report.summary.fastestFull.sourceArtifact, 'text-trim-cost-decomposition.json');
  assert.equal(report.summary.fastestFull.mibPerSec, 185.5);
  assert.equal(report.summary.fastestFullRemainingMiBPerSec, 14.5);
  assert.equal(report.summary.requiredSpeedupToTarget, 1.08);
  assert.equal(report.summary.fastestWithoutText.sourceArtifact, 'text-trim-cost-decomposition-4gib.json');
  assert.equal(report.summary.fastestWithoutText.mibPerSec, 252.36);
  assert.equal(report.summary.fastestWithoutText.fullStringParity, false);
  assert.equal(report.summary.maximumTextOmissionSpeedup, 1.41);
  assert.equal(report.summary.maximumNoTrimSpeedup, 1.02);
  assert.equal(report.summary.maximumFoldTrimSpeedup, 0.8);
  assert.equal(report.summary.negativeCandidateCount, 9);
  assert.equal(report.summary.conclusionAllowed, false);
  assert.deepEqual(report.summary.sourceConsumption.parserInput, [
    'Rows use StreamReaderSync over a synchronous Iterable<Uint8Array[]> generated by byteBatches(fixture).',
  ]);
  assert.deepEqual(report.summary.sourceConsumption.arrayBufferConsumption, [
    'The corpus file is read once as a seed buffer and sliced into Uint8Array views; measured rows consume synchronous Iterable<Uint8Array[]> parser pulls, not a pure ReadableStream and not one full 1 GiB ArrayBuffer parser input.',
  ]);
  assert.deepEqual(report.summary.sourceConsumption.batchBackpressure, [
    'byteBatches(fixture) yields one grouped Uint8Array[] batch per synchronous parser pull and does not prebuild the repeated 1 GiB+ stream.',
  ]);
  assert.deepEqual(report.summary.sourceConsumption.readableStreamScope, [
    'This Node/Bun large matrix does not consume a pure ReadableStream directly; browser fetch streaming rows are measured in browser-candidate-headroom.',
  ]);

  const fourGiB = report.sameScalePairs.find(row => row.sizeGiB === 4);
  assert.ok(fourGiB);
  assert.equal(fourGiB.full.mibPerSec, 178.86);
  assert.equal(fourGiB.withoutText.mibPerSec, 252.36);
  assert.equal(fourGiB.withoutTextSpeedup, 1.41);
  assert.equal(fourGiB.omittedTextStringReads, 67949424);

  assert.ok(report.negativeRows.some(row =>
    row.family === 'repeated-text-value-cache'
    && row.candidate.id === 'rawFrameNameIdTextCache'
    && row.candidate.mibPerSec === 129.31
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'long-ascii-text-fast-path'
    && row.candidate.id === 'rawFrameNameIdLongAsciiText'
    && row.candidate.mibPerSec === 71.21
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'medium-ascii-text-fast-path'
    && row.candidate.id === 'rawFrameNameIdMediumAsciiText'
    && row.candidate.mibPerSec === 170.16
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'unrolled-medium-ascii-text-fast-path'
    && row.candidate.id === 'rawFrameNameIdUnrolledMediumAsciiText'
    && row.candidate.mibPerSec === 170.59
    && row.candidate.counters.unrolledMediumAsciiTextHits === 2831232
    && row.candidate.counters.unrolledMediumAsciiTextFallbacks === 3539040
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'bounded-long-text-value-cache'
    && row.candidate.id === 'rawFrameNameIdLongTextCache'
    && row.candidate.mibPerSec === 141.85
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'text-trim-boundary-guard'
    && row.candidate.id === 'rawFrameNameIdTrimGuard'
    && row.candidate.mibPerSec === 109.56
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'ascii-byte-pretrim-before-decode'
    && row.candidate.id === 'rawFrameNameIdAsciiPreTrim'
    && row.candidate.mibPerSec === 106.35
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.negativeRows.some(row =>
    row.family === 'all-ascii-span-materialization'
    && row.candidate.id === 'rawFrameNameIdAllAsciiSpans'
    && row.candidate.mibPerSec === 68.63
    && row.candidatePreservesFullStringParity === true
    && row.rejectedForFullTarget === true
  ));
  assert.ok(report.findings.some(finding =>
    finding.id === 'text-cdata-omission-crosses-target'
    && finding.classification === 'HEADROOM_EVIDENCE_PRESENT'
  ));
  assert.ok(report.findings.some(finding =>
    finding.id === 'trim-only-not-enough'
    && finding.classification === 'NEGATIVE_RESULT'
  ));

  const markdown = readFileSync(mdOut, 'utf8');
  assert.match(markdown, /# Text Materialization Frontier/);
  assert.match(markdown, /Fastest full-string row: rawFrameNameId from text-trim-cost-decomposition\.json at 185\.50 MiB\/s/);
  assert.match(markdown, /1\.08x speedup required/);
  assert.match(markdown, /Fastest without-text row: withoutTextStrings from text-trim-cost-decomposition-4gib\.json at 252\.36 MiB\/s/);
  assert.match(markdown, /## Source Consumption/);
  assert.match(markdown, /synchronous Iterable<Uint8Array\[\]>/);
  assert.match(markdown, /not a pure ReadableStream and not one full 1 GiB ArrayBuffer parser input/);
  assert.match(markdown, /one grouped Uint8Array\[\] batch per synchronous parser pull/);
  assert.match(markdown, /\| 4\.00 GiB \| 178\.86 \| 182\.11 \| n\/a \| 252\.36 \| 1\.41x \| 67,949,424 \|/);
  assert.match(markdown, /repeated-text-value-cache/);
  assert.match(markdown, /bounded-long-text-value-cache/);
  assert.match(markdown, /medium-ascii-text-fast-path/);
  assert.match(markdown, /unrolled-medium-ascii-text-fast-path/);
  assert.match(markdown, /long-ascii-text-fast-path/);
  assert.match(markdown, /bounded long-text cache/);
  assert.match(markdown, /fold-trimmed-text-checksum/);
  assert.match(markdown, /text-trim-boundary-guard/);
  assert.match(markdown, /ascii-byte-pretrim-before-decode/);
  assert.match(markdown, /all-ascii-span-materialization/);
  assert.match(markdown, /Rows that omit text\/CDATA strings identify headroom but are not full-string StAX counterexamples/);
  assert.match(markdown, /A future 200 MiB\/s\+ bounded-memory full-string row remains a counterexample/);
});

function resetTmp() {
  rmSync(tmpDir, { recursive: true, force: true });
  mkdirSync(tmpDir, { recursive: true });
  for (const filePath of [jsonOut, mdOut]) {
    if (existsSync(filePath)) {
      rmSync(filePath);
    }
  }
}
